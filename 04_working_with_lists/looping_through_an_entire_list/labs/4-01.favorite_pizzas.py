# Exercise 4-01: Favorite Pizza
# Demonstrating list iteration using a for loop.

pizzas = ['pepperoni', 'margherita', 'hawaiian', 'veggie']

# Print a personalized statement for each pizza type
for pizza in pizzas:
    print(f"I really love {pizza.title()} pizza!")

# Post-loop summary statement
print("\nI really love all these types of pizza!")
